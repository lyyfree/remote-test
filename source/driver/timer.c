#include "timer.h"
void Timer0_Init(void)
{
	TMOD = (TMOD&0xFC)|0x01; 		//模式选择: 定时器0，模式1。
    /*
    
    7 GATE1定时器1门控控制位，1有效。有效时定时器1由INT1控制开关
    6 CT1
        定时器1计数器/定时器选择位
        0：定时器，时钟为系统时钟12分频
        1：计数器，时钟为T1输入时钟
    5-4 T1M1 [T1M1,T1M0]为定时器1模式选择位
        00：模式0，TL1和TH1组成13位定时器/计数器
        01：模式1，TL1和TH1组成16位定时器/计数器
        10：模式2，TL1作为8位定时器/计数器，TH1作为自动重载寄存器
        11：模式3，此模式会锁住TH1/TL1，等效于TR1=0
    3 GATE0定时器0门控控制位，1有效。有效时定时器0由INT0控制开关
    2 CT0
        定时器0计数器/定时器选择位
        0：定时器，时钟为系统时钟12分频
        1：计数器，时钟为T0输入时钟
    1-0 T0M1 [T0M1,T0M0]为定时器0模式选择位
        00：模式0，TL0和TH0组成13位定时器/计数器
        01：模式1，TL0和TH0组成16位定时器/计数器
        10：模式2，TL0作为8位定时器/计数器，TH0作为自动重载寄存器
        11：模式3，TL0和TH0作为两个完全独立的8位定时器/计数器
    */
	TH0 = TH_VAL0;    				//高8位装初值
	TL0 = TL_VAL0;    				//低8位装初值
	
	TR0 = 0;       					//定时器0使能  
	ET0 = 1;       					//定时器0中断使能
}



void Timer1_Init(void)
{
	TMOD = (TMOD&0xCF)|0x10; 		
	TH1 = TH_VAL1;    				
	TL1 = TL_VAL1;    				
	PT1 = 1;
	TR1 = 1;       					
	ET1 = 1;       					
}